/**
 * License registry.
 *
 * Every asset must name one of these ids. The registry answers three questions
 * that actually decide whether a video survives:
 *
 *   1. Can I use this in a monetized video?           -> commercialUse
 *   2. Can I edit / remix / restyle it?               -> derivatives
 *   3. Will the audio get fingerprinted and claimed?  -> contentIdRegistered
 *
 * (3) is the one nobody checks and it is where most revenue leaks.
 */
import type { AssetKind } from "./types.ts";

export interface License {
  id: string;
  name: string;
  url?: string;
  /** Usable when the output earns money. */
  commercialUse: boolean;
  /** May be edited, restyled, cut into a new work. */
  derivatives: boolean;
  attributionRequired: boolean;
  /** Derivative works inherit this license (viral licensing risk). */
  shareAlike: boolean;
  /**
   * true  -> audio is enrolled in Content ID / equivalent fingerprinting
   * false -> audio is not claimed
   * "unknown" -> assume claimed for audio kinds
   * "n/a" -> not an audio asset
   */
  contentIdRegistered: boolean | "unknown" | "n/a";
  /** Asset kinds this license can legitimately cover. Omit for all. */
  kinds?: AssetKind[];
  notes?: string;
}

