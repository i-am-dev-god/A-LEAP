/** Licenses that only make sense for particular asset kinds. */
const AUDIO_KINDS: AssetKind[] = ["audio", "music", "sfx", "voice"];

export function isAudioKind(kind: AssetKind): boolean {
  return AUDIO_KINDS.includes(kind);
}

export function getLicense(id: string | undefined): License | undefined {
  if (!id) return undefined;
  return LICENSES[id];
}

/**
 * Resolve whether audio will be fingerprinted. For audio the default on an
 * unpinned license is "assume yes" — asymmetrically safer.
 */
export function effectiveContentId(asset: {
  kind: AssetKind;
  license?: string;
  contentIdRegistered?: boolean | "unknown";
}): boolean | "unknown" | "n/a" {
  if (!isAudioKind(asset.kind)) return "n/a";
  if (typeof asset.contentIdRegistered === "boolean") return asset.contentIdRegistered;
  if (asset.contentIdRegistered === "unknown") return "unknown";
  const lic = getLicense(asset.license);
  if (!lic) return "unknown";
  // A license marked "n/a" simply has no opinion about audio fingerprinting.
  return lic.contentIdRegistered === "n/a" ? false : lic.contentIdRegistered;
}
